#!/usr/bin/env python3
"""
Еталонні числа «Сфери» для тестів: запускає саме docs/StyleRef/U1Glaze/tools/globe_slots.py (без копії формул)
і пише Assets/Tests/EditMode/Meta/GlobeSlotsReference.cs — масиви, з якими GlobeSlotsTests звіряє порт
InkFlow.Meta.GlobeSlots до 0.001.

    python3 Tools/globe-reference.py

Перегенеровувати, лише коли змінився еталон (і тоді порт мусить змінитись так само).
"""
import importlib.util
import os
import random
import sys

sys.dont_write_bytecode = True  # не лишати __pycache__ у теці еталона

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "docs", "StyleRef", "U1Glaze", "tools", "globe_slots.py")
OUT = os.path.join(ROOT, "Assets", "Tests", "EditMode", "Meta", "GlobeSlotsReference.cs")

spec = importlib.util.spec_from_file_location("globe_slots", SOURCE)
gs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gs)

LAYOUT_COUNTS = range(2, 13)            # «Сфера» — до 8; 9…12 — запас на зміну порогу
LAYOUT_SEEDS = range(1, 11)             # seed планети = 1 + PlanetType (9 типів) і ще один
PROJECTION_COUNTS = range(2, 9)
PROJECTION_SEEDS = (1, 3, 9)
PROJECTIONS = ((30.0, 16.0), (-75.5, 16.0), (400.0, 0.0), (210.0, 25.0))
RANDOM_SEEDS = (0, 1, 7919, 3051541, 2 ** 33 + 5)


def num(v):
    return f"{v:.6f}"


def main():
    lines = []
    w = lines.append
    w("// <auto-generated> Tools/globe-reference.py з docs/StyleRef/U1Glaze/tools/globe_slots.py — не правити руками. </auto-generated>")
    w("namespace InkFlow.Tests.Meta")
    w("{")
    w("    internal static class GlobeSlotsReference")
    w("    {")

    w("        /// <summary>random.Random(seed).random() — перші п'ять чисел.</summary>")
    w("        public static readonly (long seed, double[] values)[] Randoms =")
    w("        {")
    for seed in RANDOM_SEEDS:
        rnd = random.Random(seed)
        w(f"            ({seed}L, new[] {{ {', '.join(num(rnd.random()) for _ in range(5))} }}),")
    w("        };")
    w("")

    w("        /// <summary>layout(n, seed): сторона й (lat, lon, psi) кожної комірки підряд.</summary>")
    w("        public static readonly (int n, int seed, double size, double[] slots)[] Layouts =")
    w("        {")
    for n in LAYOUT_COUNTS:
        for seed in LAYOUT_SEEDS:
            slots = gs.layout(n, seed)
            flat = []
            for s in slots:
                flat += [s["lat"], s["lon"], s["psi"]]
            w(f"            ({n}, {seed}, {num(slots[0]['size'])}, new[] {{ {', '.join(num(v) for v in flat)} }}),")
    w("        };")
    w("")

    w("        /// <summary>project(slot, rot, tilt) для кожної комірки layout(n, seed): x, y, depth, m00, m01, m10, m11,")
    w("        /// alpha, shade, pip_angle, svd t1, sx, sy, t2 — по 14 чисел на комірку.</summary>")
    w("        public static readonly (int n, int seed, double rot, double tilt, double[] values)[] Projections =")
    w("        {")
    for n in PROJECTION_COUNTS:
        for seed in PROJECTION_SEEDS:
            slots = gs.layout(n, seed)
            for rot, tilt in PROJECTIONS:
                flat = []
                for s in slots:
                    p = gs.project(s, rot, tilt)
                    t1, sx, sy, t2 = gs.svd2(p["m"])
                    flat += [p["x"], p["y"], p["depth"], *p["m"], gs.alpha(p["depth"]), gs.shade(p["depth"]),
                             gs.pip_angle(s, rot), t1, sx, sy, t2]
                w(f"            ({n}, {seed}, {rot}, {tilt}, new[] {{ {', '.join(num(v) for v in flat)} }}),")
    w("        };")
    w("    }")
    w("}")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"written {os.path.relpath(OUT, ROOT)}: {os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
