namespace InkFlow.Core
{
    /// <summary>
    /// Дії Клякса (майстер-док §6). Бос ЗАВЖДИ телеграфує намір за хід наперед
    /// (§18 інваріант 8) — рандом не карає зненацька.
    /// </summary>
    public enum BossActionType : byte
    {
        None = 0,

        /// <summary>Губка: злизує колір з одного пофарбованого сегмента (не з того самого двічі поспіль).</summary>
        Sponge = 1,

        /// <summary>Плювок: перефарбовує одну краплю гравця в інший колір.</summary>
        SpitRepaint = 2,

        /// <summary>Плювок: лишає кляксу-перешкоду, що блокує клітинку, поки поруч не вибухне.</summary>
        SpitBlot = 3
    }
}
